import { expect, test } from "@playwright/test";
import { wizardStep } from "../e2e/workspace-flows.js";

test("real owner form persists custom models and the connection check sends the saved parameters", async ({ page }) => {
  const baseUrl = "https://ai.acceptance.test/v1";
  await page.goto("/login");
  await page.getByLabel("邮箱或手机号").fill("owner@acceptance.test");
  await page.getByLabel("密码", { exact: true }).fill("Acceptance-Only-Password-2026!");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await expect(page).toHaveURL("http://127.0.0.1:3100/");
  await page.goto("/ai/settings");
  await page.getByLabel("启用本组织 AI 工作洞察").check();
  await page.getByLabel("AI Base URL", { exact: true }).fill(baseUrl);
  await page.getByLabel("模型标识", { exact: true }).fill("acceptance/my-arbitrary-model:v2");
  await page.getByLabel("API Key", { exact: true }).fill("acceptance-key-only");
  await wizardStep(page, 1, "ai");
  await page.getByLabel("最大输出 Token", { exact: true }).fill("8192");
  await page.getByLabel("请求超时（秒）", { exact: true }).fill("90");
  await page.getByLabel("最大尝试次数", { exact: true }).fill("3");
  await page.getByLabel("温度（Temperature，可选）", { exact: true }).fill("0");
  await page.getByLabel("Top P（可选）", { exact: true }).fill("0.8");
  await page.getByLabel("输出 Token 参数", { exact: true }).selectOption("max_completion_tokens");
  await page.getByLabel("响应格式", { exact: true }).selectOption("json_object");
  await page.getByLabel("供应商扩展参数（JSON，可选）", { exact: true }).fill('{"reasoning_effort":"high","enable_thinking":false}');
  await wizardStep(page, 3, "ai");
  await page.getByLabel("当前 Owner 密码", { exact: true }).fill("Acceptance-Only-Password-2026!");
  await page.getByRole("button", { name: "保存并测试新配置" }).click();
  await expect(page.getByRole("status").filter({ hasText: "配置已保存，连接测试成功" })).toBeVisible();
  const { items: calls } = await (await page.request.get("/__acceptance/ai-provider-calls")).json();
  expect(calls).toHaveLength(1);
  expect(calls[0]).toMatchObject({ url: `${baseUrl}/chat/completions`, acceptanceKeyMatched: true, body: { model: "acceptance/my-arbitrary-model:v2", max_completion_tokens: 8192, temperature: 0, top_p: 0.8, response_format: { type: "json_object" }, reasoning_effort: "high", enable_thinking: false } });
  expect(calls[0]!.body).not.toHaveProperty("max_tokens");
  const saved = await (await page.request.get("/api/ai/settings")).json();
  expect(saved).toMatchObject({ model: "acceptance/my-arbitrary-model:v2", baseUrl, hasApiKey: true, generationOptions: { requestTimeoutMs: 90000, maxAttempts: 3, extraBody: { reasoning_effort: "high", enable_thinking: false } } });
  expect(JSON.stringify(saved)).not.toContain("acceptance-key-only");
  await page.reload();
  await expect(page.getByLabel("模型标识", { exact: true })).toHaveValue("acceptance/my-arbitrary-model:v2");
  await expect(page.getByLabel("API Key", { exact: true })).toHaveValue("");
});
